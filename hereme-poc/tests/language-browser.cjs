'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {chromium}=require('playwright');
const data=fs.mkdtempSync(path.join(os.tmpdir(),'hereme-language-browser-'));
process.env.HEREME_DATA_DIR=data;
process.env.HEREME_ENV='test';
const app=require('../server/index');
const services=require('../server/services');

(async()=>{
  const server=await new Promise(resolve=>{const running=app.listen(0,'127.0.0.1',()=>resolve(running));});
  let browser;
  try{
    const base=`http://127.0.0.1:${server.address().port}`;
    browser=await chromium.launch({headless:true});
    const first=await browser.newContext({locale:'en-US',viewport:{width:390,height:844}});
    const page=await first.newPage();
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base+'/chat');
    await page.getByRole('tab',{name:'Opprett konto',selected:true}).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'nb');
    await page.locator('.auth-dialog [data-language=en]').click();
    await page.getByText('Create an account or log in to use chat.',{exact:true}).waitFor();
    await page.locator('.auth-dialog [data-language=nb]').click();
    await page.goto(base);
    await page.locator('.menu-button').click();
    await page.locator('[data-action=auth-login]').click();
    await page.getByRole('tab',{name:'Logg inn',selected:true}).waitFor();
    await page.locator('[data-auth-form=login] input[name=name]').fill('MissingAccount');
    await page.locator('[data-auth-form=login] input[name=recovery_key]').fill('incorrect-code-for-browser-test');
    await page.locator('[data-auth-form=login] button').click();
    await page.locator('.auth-error').getByText('Pseudonym eller nøkkel er feil.').waitFor();
    await page.keyboard.press('Escape');
    await page.locator('.menu-button').click();
    await page.locator('.language-menu [data-language=en]').click();
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    await page.getByRole('heading',{name:'Account'}).waitFor();
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    await page.locator('.menu-button').click();
    await page.locator('[data-action=auth-register]').click();
    await page.getByRole('heading',{name:'Create account'}).waitFor();
    await page.locator('[data-auth-form=register] input[name=name]').fill('UnsentName');
    await page.locator('.auth-dialog [data-language=nb]').click();
    assert.equal(await page.locator('[data-auth-form=register] input[name=name]').inputValue(),'UnsentName');
    assert.equal(await page.locator('html').getAttribute('lang'),'nb');
    await page.locator('.auth-dialog [data-language=en]').click();
    assert.equal(await page.locator('[data-auth-form=register] input[name=name]').inputValue(),'UnsentName');
    await page.locator('[data-auth-form=register] button').click();
    await page.locator('.auth-recovery').waitFor();
    const current=await first.request.get(base+'/api/me').then(response=>response.json());
    assert.equal(current.user.preferred_language,'en');
    const cookie=await first.cookies();
    const second=await browser.newContext({locale:'nb-NO'});
    await second.addCookies(cookie);
    const other=await second.newPage();
    await other.goto(base);
    await other.waitForFunction(()=>document.documentElement.lang==='en');
    await other.goto(base+'/privacy.html');
    await other.getByRole('heading',{name:'Privacy'}).waitFor();
    assert.equal(await other.locator('[data-language]').count(),0);
    assert.deepEqual(errors,[]);
    await second.close();await first.close();
    console.log('Language selection and account preference passed.');
  }finally{
    await browser?.close();
    await new Promise(resolve=>server.close(resolve));
    services.db.close();
    fs.rmSync(data,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
