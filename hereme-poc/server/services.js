'use strict';
const {db,dataDir}=require('./db');
const {runtimeConfig}=require('./config');
const {createAuditService}=require('./domain/audit');
const {createIdentityService}=require('./domain/identity');
const {createMediaService}=require('./domain/media');
const {createAvatarService}=require('./domain/avatars');
const {createPostService}=require('./domain/posts');
const {createInteractionService}=require('./domain/interactions');
const {createModerationService}=require('./domain/moderation');
const {createAccountService}=require('./domain/accounts');
const {createChatService}=require('./domain/chat');
const {createAdministrationService}=require('./domain/administration');
const {createRateLimiter}=require('./domain/rate-limit');
const {createVideoService}=require('./domain/video');
const {createArticleService}=require('./domain/articles');
const {createContentRevisionService}=require('./domain/content-revisions');
const {createLocationService}=require('./domain/locations');
const {createVerificationService}=require('./domain/verification');
const {createProfileService}=require('./domain/profile');
const {createPublicProfileService}=require('./domain/public-profiles');
const {createSharePreviewService}=require('./domain/share-previews');
const {createNotificationService}=require('./domain/notifications');
const {createPushService}=require('./domain/push');
const {createPasskeyService}=require('./domain/passkeys');
const config=runtimeConfig();
const audit=createAuditService(db);
const identity=createIdentityService(db,config);
const passkeys=createPasskeyService(db,config,{identity,audit});
const media=createMediaService(db,dataDir,config);
const avatars=createAvatarService(db,dataDir,{media,audit});
avatars.cleanup();
const articles=createArticleService(db,dataDir,{media,audit,config});
const contentRevisions=createContentRevisionService(db,{articles,audit});
articles.cleanup();
const posts=createPostService(db,{media,audit,articles,config});
const sharePreviews=createSharePreviewService(posts,dataDir);
const notifications=createNotificationService(db);
const push=createPushService(db,config);
const interactions=createInteractionService(db,{audit,notifications});
const moderation=createModerationService(db,{audit,identity});
const accounts=createAccountService(db,{audit,identity,avatars});
const chat=createChatService(db,dataDir,config,{audit,notifications,avatars});
chat.cleanup();
const administration=createAdministrationService(db,dataDir,{audit,identity,avatars});
const rate=createRateLimiter();
const video=createVideoService(db,dataDir,config,{audit});
const locations=createLocationService(db,config);
const verification=createVerificationService(db,config,{audit});
const profile=createProfileService(db,{posts,avatars});
const publicProfiles=createPublicProfileService(db,{avatars});
module.exports={db,dataDir,config,audit,identity,passkeys,media,avatars,posts,articles,contentRevisions,sharePreviews,interactions,moderation,administration,accounts,chat,rate,video,locations,verification,profile,publicProfiles,notifications,push};
